// Practice lessons for the TCM Expansions tab: every situation the video walks through,
// redrawn with invented prices so it can be stepped candle by candle. Each lesson has:
//  - the candles (most written as moves from the previous close, see `walk`);
//  - the expansion the rules read (`anchor`), and later ones it moves to (`next`);
//  - `notes`: what the video says at that point, shown as the replay reaches the candle;
//  - `marks`: what the rules engine does not draw itself (order blocks, FVGs, failure
//    swings, old highs and lows, session times), drawn as the replay reaches them.
// The candles are illustrations, not market data; `ref` is where the video covers it.
import type { Bar } from './expansion';

export type MarkTone = 'muted' | 'watch' | 'bull' | 'bear';

/** Something the lesson draws besides the range. It appears once the replay reaches `at` (default: where it starts). */
export type LessonMark =
  | { kind: 'level'; label: string; price: number; from: number; at?: number; tone?: MarkTone }
  | { kind: 'zone'; label: string; top: number; bottom: number; from: number; to?: number; at?: number; tone?: MarkTone }
  | { kind: 'time'; label: string; index: number; at?: number }
  | { kind: 'tag'; label: string; index: number; above: boolean; at?: number; tone?: MarkTone };

export interface LessonNote {
  /** Shown once the replay reaches this candle, until the next note. */
  at: number;
  text: string;
}

export interface Lesson {
  key: string;
  title: string;
  /** What the lesson shows, one or two sentences. */
  note: string;
  /** Video timestamp, "mm:ss". */
  ref: string;
  /** Timeframe shown in the pane header. */
  timeframe: string;
  minutes: number;
  bars: Bar[];
  /** A candle of the expansion the lesson reads first. */
  anchor: number;
  /** Later expansions: from candle `at` on, the lesson reads the one at `anchor`. */
  next?: { at: number; anchor: number }[];
  /** Where the replay starts (last candle shown). */
  start: number;
  /** The lesson's own smallest range worth trading (a 1-minute or daily chart differs). */
  minSize?: number;
  notes: LessonNote[];
  marks?: LessonMark[];
}

type Ohlc = readonly [number, number, number, number];
/** One candle as a move: close change from its open, upper wick, lower wick, and an optional gap at the open. */
type Move = readonly [number, number, number] | readonly [number, number, number, number];

/** New York wall-clock time written as UTC, like the companion's candles. */
const ny = (y: number, mo: number, d: number, h: number, mi: number) => Date.UTC(y, mo - 1, d, h, mi) / 1000;
const FRI_0930 = ny(2026, 2, 13, 9, 30);

function bars(rows: readonly Ohlc[], minutes = 5, base = FRI_0930): Bar[] {
  return rows.map(([open, high, low, close], i) => ({ t: base + i * minutes * 60, open, high, low, close }));
}

/** Candles from moves: each opens at the previous close (plus any gap). */
function walk(start: number, moves: readonly Move[], minutes = 5, base = FRI_0930): Bar[] {
  let prev = start;
  return moves.map(([dc, up, dn, gap = 0], i) => {
    const open = prev + gap;
    const close = open + dc;
    prev = close;
    return { t: base + i * minutes * 60, open, close, high: Math.max(open, close) + up, low: Math.min(open, close) - dn };
  });
}

